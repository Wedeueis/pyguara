def _title(facts: ProjectFacts) -> str:
    """Return the heading for a brand-new canonical file.

    Args:
        facts: What is known about the project.

    Returns:
        A Markdown heading.
    """
    return f"# {facts.name}\n\nInstructions for coding agents working in this project."


def _render_canonical(facts: ProjectFacts) -> str:
    """Render the generated region of `AGENTS.md`.

    Ordered by what an agent needs first: what this is, how to run it,
    then the vocabulary, then the Studio surface. An agent that reads only
    the first screen should still be able to act.

    Args:
        facts: What to write.

    Returns:
        The Markdown region, without markers.
    """
    sections: list[str] = []

    if facts.summary:
        sections.append(facts.summary.strip())
    else:
        sections.append(
            f"`{facts.name}` is a game built on the PyGuara engine: a "
            f"code-first Python 2D engine with an Entity-Component-System "
            f"core, a dependency-injection container and an event bus. "
            f"Scenes, components and systems are authored in Python; the "
            f"data files beside them are things a human could have written "
            f"by hand."
        )

    if facts.commands:
        lines = ["## Commands", ""]
        for description, command in facts.commands:
            lines.append(f"- {description}: `{command}`")
        sections.append("\n".join(lines))

    sections.append(_render_engine_conventions())

    if facts.project_map is not None:
        rendered = facts.project_map.to_markdown(budget=6000)
        if rendered:
            sections.append(rendered)

    sections.append(_render_studio_section())

    if facts.conventions:
        lines = ["## Project conventions", ""]
        lines.extend(f"- {convention}" for convention in facts.conventions)
        sections.append("\n".join(lines))

    return "\n\n".join(sections)


def _render_engine_conventions() -> str:
    """Render the engine rules an agent will otherwise get wrong.

    Chosen by what actually trips a newcomer to this engine, not by what
    is architecturally interesting. Each one is a mistake worth one line
    of prevention.

    Returns:
        A Markdown section.
    """
    return "\n".join(
        [
            "## Engine conventions",
            "",
            "- **Components are data.** A component is a dataclass with no",
            "  methods; behaviour lives in a system or in free functions",
            "  beside it. `BaseComponent.__init_subclass__` raises at class",
            "  definition time if a component declares a method.",
            "- **Never import the rendering backend.** Game code uses the",
            "  `IRenderer` / `UIRenderer` protocols through the DI container.",
            "  A direct `import pygame` in game code is a layering break.",
            "- **Query through the manager.** `entity_manager.get_entities_with("
            "Transform, Sprite)`",
            "  is an indexed lookup; iterating every entity and testing is not.",
            "- **Mutating a component needs a notification.** After writing a",
            "  field, call `entity_manager.notify_component_changed(entity_id, "
            "ComponentType)`,",
            "  or anything mirroring it -- physics bodies, render batches, the",
            "  spatial index -- keeps the old value.",
            "- **One component of each type per entity.** Replacing one is a",
            "  remove followed by an add.",
            "- **Two kinds of parent.** `Transform` parenting is spatial;",
            "  `ChildOf` is ownership and cascades on destroy. Set `ChildOf`",
            "  through `entity_manager.set_parent()`, never `add_component`.",
            "- **Fixed vs variable update.** Physics and game logic run in",
            "  `fixed_update` at a constant rate; rendering and animation run",
            "  in `update` at the display rate.",
        ]
    )


def _render_studio_section() -> str:
    """Render how to drive the editor from an agent.

    The part an agent cannot discover: that the surface exists at all.

    Returns:
        A Markdown section.
    """
    return "\n".join(
        [
            "## Authoring through PyGuara Studio",
            "",
            "Studio exposes the scene as a set of operations, so a scene can",
            "be read and edited without a window. Two transports, the same",
            "operations behind both:",
            "",
            "```bash",
            "# JSON lines on stdio -- no extra dependency.",
            "pyguara studio ops",
            "",
            "# Model Context Protocol -- needs the `studio` extra.",
            "pyguara studio mcp",
            "```",
            "",
            "To wire the MCP server into an agent, point it at",
            "`pyguara studio mcp` as a stdio server.",
            "",
            "Working rules, which the operations themselves enforce:",
            "",
            "- Call `project_overview` first in an unfamiliar project, then",
            "  `scene_summary`. `scene_tree` is the full read and is large.",
            "- Call `component_schema` before setting a field on a component",
            "  type you have not used. It carries the field types, the",
            "  defaults, and an enum field's valid members.",
            "- Entities are named by id, and ids survive undo, redo and",
            "  reload -- an id from one call still means the same entity in",
            "  the next.",
            "- Every edit returns the diff it produced. Check your own work",
            "  from the reply rather than re-reading the scene.",
            "- Every edit is undoable through `history`, and every action,",
            "  including the failures, is in `journal`.",
            "- An error names the alternative. A wrong component or field",
            "  name comes back with the closest match, so correct from the",
            "  message rather than listing everything again.",
        ]
    )


def _build_shim(project_root: Path, shim: ShimKind) -> InstructionFile:
    """Build one per-tool shim that defers to the canonical file.

    An import line rather than a copy. Claude Code in particular never
    merges `CLAUDE.md` with `AGENTS.md` -- if both exist, `CLAUDE.md` wins
    outright -- so a copy would become a second source of truth that
    silently rots while appearing authoritative.

    Args:
        project_root: The project directory, for reading an existing file.
        shim: Which tool to write for.

    Returns:
        The file.
    """
    if shim is ShimKind.CURSOR:
        generated = "\n".join(
            [
                "Follow the instructions in @AGENTS.md.",
                "",
                "That file is generated from the project; edit it, not this one.",
            ]
        )
        header = "\n".join(
            [
                "---",
                "description: PyGuara project conventions",
                "alwaysApply: true",
                "---",
                "",
                "# PyGuara",
            ]
        )
        path = CURSOR_RULE_PATH
    else:
        tool = "Claude Code" if shim is ShimKind.CLAUDE else "Gemini CLI"
        other = "AGENTS.md"
        generated = "\n".join(
            [
                f"@{other}",
                "",
                f"{tool} reads this file rather than `{other}`, and does not",
                f"merge the two -- so `{other}` is imported above instead of",
                "being copied here. Add anything tool-specific outside the",
                "generated block; it will be preserved.",
            ]
        )
        header = f"# {project_root.name}"
        path = "CLAUDE.md" if shim is ShimKind.CLAUDE else "GEMINI.md"

    return InstructionFile(
        path=path,
        content=merge_generated(_read(project_root / path), generated, header=header),
        generated=generated,
    )


