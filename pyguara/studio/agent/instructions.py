def _read(path: Path) -> str | None:
    """Return a file's text, or None when it is absent or unreadable.

    Args:
        path: The file to read.

    Returns:
        Its contents, or None.
    """
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _has_ruff(project_root: Path) -> bool:
    """Whether the project is configured for ruff.

    Args:
        project_root: The project directory.

    Returns:
        True when ruff appears in its configuration.
    """
    if (project_root / "ruff.toml").exists() or (project_root / ".ruff.toml").exists():
        return True
    pyproject = _read(project_root / "pyproject.toml")
    return pyproject is not None and "[tool.ruff" in pyproject


def _has_mypy(project_root: Path) -> bool:
    """Whether the project is configured for mypy.

    Args:
        project_root: The project directory.

    Returns:
        True when mypy appears in its configuration.
    """
    if (project_root / "mypy.ini").exists():
        return True
    pyproject = _read(project_root / "pyproject.toml")
    return pyproject is not None and "[tool.mypy" in pyproject


